// Builds www/ for the Capacitor Android app from the browser version of OJAS.
//
// Only frontend files are copied: every *.html page in the project root plus the local scripts and
// stylesheets those pages reference (followed from their <script src> / <link href> tags).
// Backend code (*.py, routes/), firmware/, supabase/, .env, .git and node_modules are never copied.
// The browser version in the project root is not modified.
//
// Settings (environment variables, not secrets):
//   OJAS_API_BASE  Flask backend the app talks to, e.g. http://192.168.1.20:5000 or https://ojas-api.example.com
//                  (inside the app "localhost" / 127.0.0.1 means the phone, not your laptop)
//   OJAS_WEB_BASE  Address where the browser version is hosted online (used later for the
//                  password-reset email link and the Medical ID QR code), e.g. https://ojas.example.com
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, normalize, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'www');
const BLOCKED = /(^|[\\/])(\.env|\.git|node_modules|routes|firmware|supabase|android|www|scripts|venv|__pycache__)([\\/]|$)|\.py$/;

const pages = readdirSync(ROOT).filter((f) => f.endsWith('.html')).sort();
const files = new Set(pages);
for (const page of pages) {
  const html = readFileSync(join(ROOT, page), 'utf8');
  for (const [, ref] of html.matchAll(/<(?:script|link)\b[^>]*?\b(?:src|href)="([^"]+)"/g)) {
    if (/^(?:[a-z]+:)?\/\//i.test(ref) || ref.startsWith('#') || ref.startsWith('data:')) continue;   // external / anchors
    const path = normalize(ref.split(/[?#]/)[0]);
    if (path.startsWith('..') || path.startsWith(sep)) throw new Error(`${page}: reference outside the project: ${ref}`);
    files.add(path);
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const file of [...files].sort()) {
  if (BLOCKED.test(file)) throw new Error(`Refusing to copy non-frontend file: ${file}`);
  const from = join(ROOT, file);
  if (!existsSync(from)) throw new Error(`Missing file referenced by a page: ${file}`);
  mkdirSync(dirname(join(OUT, file)), { recursive: true });
  cpSync(from, join(OUT, file));
}

// Native Bluetooth for the Android app: bundle @capacitor-community/bluetooth-le into one file that
// the plain <script> pages can load (window.OjasNativeBle). In a browser it is never loaded.
buildSync({
  entryPoints: [join(ROOT, 'scripts', 'native-ble-entry.mjs')],
  outfile: join(OUT, 'vendor', 'capacitor-ble.js'),
  bundle: true, format: 'iife', platform: 'browser', target: 'es2019', minify: true, legalComments: 'none', logLevel: 'error',
});

// www/config.js: runtime settings, loaded before the other scripts on every page.
const api = (process.env.OJAS_API_BASE || '').trim().replace(/\/+$/, '');
const web = (process.env.OJAS_WEB_BASE || '').trim().replace(/\/+$/, '');
for (const [name, value] of [['OJAS_API_BASE', api], ['OJAS_WEB_BASE', web]]) {
  if (value && !/^https?:\/\/[^\s/]+/.test(value)) throw new Error(`${name} must start with http:// or https://`);
}
let config = '// Generated by scripts/build-www.mjs – do not edit; set OJAS_API_BASE / OJAS_WEB_BASE and rebuild.\n';
if (api) config += `window.OJAS_API_BASE = ${JSON.stringify(api)};\n`;
if (web) config += `window.OJAS_WEB_BASE = ${JSON.stringify(web)};\n`;
writeFileSync(join(OUT, 'config.js'), config);

// Android blocks plain http:// by default. Allow it only for the backend host, and only when
// OJAS_API_BASE uses http:// (a development server on your Wi-Fi). An https:// backend needs no
// exception. android/app/src/main/res/xml/network_security_config.xml is rewritten on every build.
const nsc = join(ROOT, 'android', 'app', 'src', 'main', 'res', 'xml', 'network_security_config.xml');
if (existsSync(dirname(nsc))) {
  const httpHost = api.startsWith('http://') ? new URL(api).hostname : null;
  const domain = httpHost
    ? `    <!-- Development backend over http (from OJAS_API_BASE). Use an https:// backend for release builds. -->
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${httpHost}</domain>
    </domain-config>
`
    : '';
  writeFileSync(nsc, `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-www.mjs from OJAS_API_BASE – rebuild instead of editing. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
${domain}</network-security-config>
`);
}

// Load config.js first on every page of the www copy (the browser version is untouched).
for (const page of pages) {
  const target = join(OUT, page);
  const html = readFileSync(target, 'utf8');
  const at = html.indexOf('<script');
  if (at === -1) continue;
  let out = `${html.slice(0, at)}<script src="config.js"></script>\n  ${html.slice(at)}`;
  out = out.replace('<script src="ble-adapter.js"></script>', '<script src="vendor/capacitor-ble.js"></script>\n  <script src="ble-adapter.js"></script>');
  writeFileSync(target, out);
}

console.log(`www/ built: ${files.size} files (${pages.length} pages) + config.js + vendor/capacitor-ble.js`);
console.log(`  OJAS_API_BASE = ${api || '(not set)'}`);
console.log(`  OJAS_WEB_BASE = ${web || '(not set)'}`);
if (api && /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:|\/|$)/.test(api)) {
  console.warn('\nWARNING: OJAS_API_BASE points to localhost. Inside the Android app that is the PHONE, not your laptop.\n'
    + 'Use your laptop\'s Wi-Fi address (e.g. http://192.168.1.20:5000, with FLASK_HOST=0.0.0.0) or your deployed backend.');
}
if (!api) {
  console.warn('\nWARNING: OJAS_API_BASE is not set. Inside the Android app the default http://127.0.0.1:5000 is the PHONE,\n'
    + 'so sign-in and all data will fail. Set it to your laptop\'s network address or your deployed backend, then rebuild.');
}
